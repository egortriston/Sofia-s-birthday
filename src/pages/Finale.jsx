import { useEffect, useState, useRef } from 'react'
import { Starfield } from '@/components/ui/starfield-1'
import './Finale.css'
import starWarsMusic from '@/music/John_Williams_-_Star_Wars_Main_Theme_and_Ambush_on_Coruscant_Zvezdnye_vojny_Ataka_klonov_(SkySound.cc).mp3'

function Finale() {
  const [showText, setShowText] = useState(false)
  const [musicPlaying, setMusicPlaying] = useState(false)
  const audioRef = useRef(null)

  useEffect(() => {
    setTimeout(() => setShowText(true), 1000)

    // Создаем аудио элемент
    audioRef.current = new Audio(starWarsMusic)
    audioRef.current.loop = true
    audioRef.current.volume = 0.5

    // Автоматически начинаем воспроизведение при загрузке страницы
    const playPromise = audioRef.current.play()
    if (playPromise !== undefined) {
      playPromise
        .then(() => {
          setMusicPlaying(true)
        })
        .catch(error => {
          console.log('Автовоспроизведение заблокировано:', error)
          // Если автовоспроизведение заблокировано, пользователь может включить вручную
        })
    }

    return () => {
      // Очистка при размонтировании
      if (audioRef.current) {
        audioRef.current.pause()
        audioRef.current = null
      }
    }
  }, [])

  const handleMusicToggle = () => {
    if (!audioRef.current) return

    if (musicPlaying) {
      audioRef.current.pause()
      setMusicPlaying(false)
    } else {
      const playPromise = audioRef.current.play()
      if (playPromise !== undefined) {
        playPromise
          .then(() => {
            setMusicPlaying(true)
          })
          .catch(error => {
            console.error('Ошибка воспроизведения:', error)
          })
      }
    }
  }

  const congratulationText = `
    АХАХАХАХАХАХХАХ
    
    С Днем Рождения еще раз тебя, Соша!
    
    Ты прошла через все испытания космоса,
    ответила на все вопросы и доказала,
    что ты настоящая звезда!
    
    Я прекрасно помню, что твой папа фанат серии Звездных войн, поэтому думаю, что вам зашла такая отсылка.
    
    Ты заслуживаешь всего самого лучшего!
    Я очень рад, что тебя встретил в том году! И надеюсь, что эта дружба протянется еще долгое время!
    Я очень долго думал над тем, как представить этот подарок. Изначально я хотел помочь с организацией путевки в Испанию. А эта должна была быть просто визитка))))
    После разузнав подробнее из разных источников, понял, что слишком много проблем как с получением визы, так и в принципе тебе одной быть там. Да и я как-будто вынуждал часть лета твоего провести так... Постепенно подарок изменялся и уходил от роли визитки в полноценный квест.
    Я начал думать о формате. Сначала все должно было быть в цветах твоего отряда, но в моменте я посчитал, что подарок от меня в чужой и не моей индентики был бы чем-то не тем.
    После нашел идеи с каруселью в космосе и подумал: "о, а это было бы круто, как раз ты рассказала, что твой папа фанат SW". Так началось долгое и в чем-то мучительное создание  
    Я надеюсь, что мои подарки никак тебя не обидели, не сделали больно и тд.
    Ты знаешь, что я очень много сил потратил и точно не хотел бы как-то обидеть тебя. Везде только шутки. От чего-то пришлось отказаться. 
    Эту часть я пишу уже во время некого недопонимания за неделю до ДР. Я не знаю как все сложится в дальнейшем. 
    Просто хочу сказать, что как-бы я когда-либо не сказал и как я бы не пошутил, ты мне всегда будешь не просто дорога, а бесценна. Один год, а такой огромный путь. Наверное, все эмоции описывает то, что перебирая все эпитиы, подходящего я так и не нашел...
    Надеюсь, что тебе понравилось это маленькое путешествие по космосу и ты не откажешь мне в передаче твоего подарка.

    
    Иногда очень сложно пожелать человеку что-то, когда у него уже все есть. 
    Ты, думаю, знаешь, что я и так все силы отдаю на то, чтобы ты была счастлива)
    Мне для этого не нужен повод. Но формат праздника требует тебе что-то пожелать.

    А желаю я тебе получить все, что ты так желала в том году, но не успела!

    Также хоть и не знакомы, но стоит и поздравить твою Маму. Для нее это тоже важный праздник и 21 год назад, я уверен, в ее жизни появился новый огонечек и смысл жизни.
    Поэтому да, поздравления тут не только тебе одной

    К сожалению, большего мне пожелать и сказать не позволяет мой статус)
    Поэтому я остановлюсь на этом.
    Еще раз спасибо тебе за тебя и еще раз с Днем Рождения!
    Пусть прибудит с тобой сила! XD
  `

  return (
    <div className="finale-page">
      <Starfield speed={0.15} starColor="rgba(255,255,255,1)" quantity={2400} />

      <button
        className="music-toggle"
        onClick={handleMusicToggle}
      >
        {musicPlaying ? '🔇 Выключить музыку' : '🔊 Включить музыку'}
      </button>

      <div className={`crawl-container ${showText ? 'visible' : ''}`}>
        <div className="crawl-text">
          {congratulationText.split('\n').map((line, index) => (
            <p key={index}>{line}</p>
          ))}
        </div>
      </div>
    </div>
  )
}

export default Finale



